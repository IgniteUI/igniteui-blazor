namespace IgniteUI.Blazor.Controls
{
    /// <summary>
    /// Semantic color of a component such as a badge, chip, or progress indicator.
    /// The actual colors come from the active theme.
    /// </summary>
    public enum StyleVariant
    {
        /// <summary>The theme's primary color.</summary>
        Primary,
        /// <summary>Informational.</summary>
        Info,
        /// <summary>Success or completion.</summary>
        Success,
        /// <summary>Warning.</summary>
        Warning,
        /// <summary>Error or destructive action.</summary>
        Danger

    }
}
