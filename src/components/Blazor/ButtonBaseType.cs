namespace IgniteUI.Blazor.Controls
{
    /// <summary>
    /// Form behavior of a button. Mirrors the HTML button <c>type</c> attribute.
    /// </summary>
    public enum ButtonBaseType
    {
        /// <summary>No default form behavior.</summary>
        Button,
        /// <summary>Resets the associated form fields to their initial values.</summary>
        Reset,
        /// <summary>Submits the associated form.</summary>
        Submit

    }
}
