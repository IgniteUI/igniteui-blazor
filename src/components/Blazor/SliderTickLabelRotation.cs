        [WCEnumName("0")]
        Zero,
        /// <summary>Labels rotated 90 degrees clockwise.</summary>
        [WCEnumName("90")]
        Ninety,
        /// <summary>Labels rotated 90 degrees counterclockwise.</summary>
        [WCEnumName("-90")]
        NegativeNinety

    }
}
