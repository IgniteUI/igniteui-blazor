namespace IgniteUI.Blazor.Controls
{
    /// <summary>
    /// Placement of a step's title relative to its indicator in an <see cref="IgbStepper"/>.
    /// </summary>
    public enum StepperTitlePosition
    {
        /// <summary>Below the indicator in a horizontal stepper, after it in a vertical one.</summary>
        Auto,
        /// <summary>Below the indicator.</summary>
        Bottom,
        /// <summary>Above the indicator.</summary>
        Top,
        /// <summary>After the indicator.</summary>
        End,
        /// <summary>Before the indicator.</summary>
        Start

    }
}
