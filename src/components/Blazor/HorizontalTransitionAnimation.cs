namespace IgniteUI.Blazor.Controls
{
    /// <summary>
    /// Transition between horizontally arranged panes, such as carousel slides or the steps of a horizontal stepper.
    /// </summary>
    public enum HorizontalTransitionAnimation
    {
        /// <summary>The new pane slides in while the old one slides out.</summary>
        Slide,
        /// <summary>The new pane fades in while the old one fades out.</summary>
        Fade,
        /// <summary>The panes switch without animation.</summary>
        None

    }
}
