namespace IgniteUI.Blazor.Controls
{
    /// <summary>
    /// When the resize handles of the tiles in an <see cref="IgbTileManager"/> are shown.
    /// </summary>
    public enum TileManagerResizeMode
    {
        /// <summary>Tiles cannot be resized.</summary>
        None,
        /// <summary>Handles appear when the pointer is over a tile.</summary>
        Hover,
        /// <summary>Handles are always visible.</summary>
        Always

    }
}
