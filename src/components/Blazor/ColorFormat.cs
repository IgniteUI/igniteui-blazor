namespace IgniteUI.Blazor.Controls
{
    /// <summary>
    /// The notation an <see cref="IgbColorPicker"/> renders its string value in.
    /// </summary>
    public enum ColorFormat
    {
        /// <summary>Hexadecimal notation, <c>#rrggbb</c>.</summary>
        Hex,
        /// <summary>RGB notation, <c>rgb(r g b)</c>.</summary>
        Rgb,
        /// <summary>HSL notation, <c>hsl(h s% l%)</c>.</summary>
        Hsl

    }
}
