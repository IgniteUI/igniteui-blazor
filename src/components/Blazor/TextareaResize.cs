namespace IgniteUI.Blazor.Controls
{
    /// <summary>
    /// How the height of an <see cref="IgbTextarea"/> can change.
    /// </summary>
    public enum TextareaResize
    {
        /// <summary>The user can drag the resize handle to change the height.</summary>
        Vertical,
        /// <summary>The height grows and shrinks to fit the content.</summary>
        Auto,
        /// <summary>Fixed height.</summary>
        None

    }
}
